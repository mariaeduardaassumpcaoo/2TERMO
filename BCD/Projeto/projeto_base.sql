DROP DATABASE IF EXISTS projeto_almoxarifado;
CREATE DATABASE projeto_almoxarifado;
USE projeto_almoxarifado;

CREATE TABLE MATERIAIS (
    ID_MATERIAIS INT AUTO_INCREMENT PRIMARY KEY,
    DESCRICAO VARCHAR(100) NOT NULL,
    NOME VARCHAR(100) NOT NULL,
    VALOR_UNITARIO DECIMAL(10,2) NOT NULL,
    UNIDADE_MEDIA VARCHAR(50) NOT NULL,
    LOCALIZACAO VARCHAR(100) NOT NULL
);

CREATE TABLE FORNECEDORES (
    ID_FORNECEDORES INT AUTO_INCREMENT PRIMARY KEY,
    CNPJ VARCHAR(20) NOT NULL UNIQUE,
    EMAIL VARCHAR(100) NOT NULL,
    NOME VARCHAR(100) NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    CIDADE VARCHAR(100)
);

CREATE TABLE ESTOQUE (
    ID_ESTOQUE INT AUTO_INCREMENT PRIMARY KEY,
    ESTOQUE_ANUAL INT NOT NULL,
    QUANTIDADE_MINIMA INT NOT NULL,
    PRATELEIRA VARCHAR(50) NOT NULL,
    QUANTIDADE_MAXIMA INT NOT NULL,
    QUANTIDADE_ATUAL INT NOT NULL
);

CREATE TABLE SETOR (
    id_setor INT AUTO_INCREMENT PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    status ENUM('disponivel', 'indisponivel') NOT NULL,
    localizacao VARCHAR(100) NOT NULL,
    responsavel VARCHAR(100) NOT NULL
);

CREATE TABLE MOVIMENTACOES (
    ID_MOVIMENTACOES INT AUTO_INCREMENT PRIMARY KEY,
    RAMAL VARCHAR(20) NOT NULL,
    DATA_MOVIMENTACAO DATETIME NOT NULL,
    OBSERVACAO VARCHAR(255),
    TIPO_MOVIMENTACAO VARCHAR(50) NOT NULL,
    MOVIMENTACOES_MENSAIS INT NOT NULL,
    ID_SETOR INT,
    FOREIGN KEY (ID_SETOR) REFERENCES SETOR(ID_SETOR)
);

CREATE TABLE FORNECE (
    ID_MATERIAIS INT,
    ID_FORNECEDORES INT,
    PRIMARY KEY (ID_MATERIAIS, ID_FORNECEDORES),
    FOREIGN KEY (ID_MATERIAIS) REFERENCES MATERIAIS(ID_MATERIAIS),
    FOREIGN KEY (ID_FORNECEDORES) REFERENCES FORNECEDORES (ID_FORNECEDORES)
);

CREATE TABLE PRECISA (
    ID_MATERIAIS INT,
    ID_ESTOQUE INT,
    PRIMARY KEY (ID_MATERIAIS, ID_ESTOQUE),
    FOREIGN KEY (ID_MATERIAIS) REFERENCES MATERIAIS (ID_MATERIAIS),
    FOREIGN KEY (ID_ESTOQUE) REFERENCES ESTOQUE (ID_ESTOQUE)
);

CREATE TABLE ENVOLVE (
    id_materiais INT,
    id_movimentacoes INT,
    PRIMARY KEY (id_materiais, id_movimentacoes),
    FOREIGN KEY (id_materiais) REFERENCES MATERIAIS(id_materiais),
    FOREIGN KEY (id_movimentacoes) REFERENCES MOVIMENTACOES(id_movimentacoes)
);