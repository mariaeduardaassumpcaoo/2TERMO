-- 8. PROCEDURE DE MOVIMENTAÇÃO

DROP PROCEDURE IF EXISTS sp_movimentar_estoque;

DELIMITER $$

CREATE PROCEDURE sp_movimentar_estoque(
    IN p_material INT,
    IN p_setor INT,
    IN p_quantidade INT,
    IN p_tipo VARCHAR(10),
    IN p_observacao VARCHAR(255)
)
BEGIN

    DECLARE v_estoque INT;

    SELECT ID_ESTOQUE INTO v_estoque
    FROM PRECISA
    WHERE ID_MATERIAIS = p_material
    LIMIT 1;

    START TRANSACTION;

    INSERT INTO MOVIMENTACOES
    (RAMAL, DATA_MOVIMENTACAO, OBSERVACAO,
    TIPO_MOVIMENTACAO, MOVIMENTACOES_MENSAIS,
    ID_SETOR, quantidade_movimentada)
    VALUES
    ('101', NOW(), p_observacao, p_tipo, 1,
    p_setor, p_quantidade);

    INSERT INTO ENVOLVE
    (ID_MATERIAIS, ID_MOVIMENTACOES)
    VALUES
    (p_material, LAST_INSERT_ID());

    IF p_tipo = 'ENTRADA' THEN

        UPDATE ESTOQUE
        SET QUANTIDADE_ATUAL = QUANTIDADE_ATUAL + p_quantidade
        WHERE ID_ESTOQUE = v_estoque;

    ELSE

        UPDATE ESTOQUE
        SET QUANTIDADE_ATUAL = QUANTIDADE_ATUAL - p_quantidade
        WHERE ID_ESTOQUE = v_estoque;

    END IF;

    COMMIT;

END $$

DELIMITER ;

