-- 1. FUNCTION CALCULAR_TOTAL_ITEM
DELIMITER $$
CREATE FUNCTION CALCULANDO_TOTAL_ITEM
(P_PRECO DECIMAL(10,2), P_QUANTIDADE INT)
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
    RETURN P_PRECO * P_QUANTIDADE;
END $$
DELIMITER;

SELECT NOME, PRECO, CALCULANDO_TOTAL_ITEM(PRECO, 4) AS TOTAL_4_UNIDADES
